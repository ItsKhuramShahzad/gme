def list_molecules():
    """Return a sorted list of molecule names in the database."""
    return sorted(MOLECULES.keys())


def get_molecule(name: str) -> dict:
    """Return the data dict for a molecule. Raises KeyError with a helpful
    message if the name is not found."""
    if name not in MOLECULES:
        raise KeyError(
            f"Molecule '{name}' not found. Available: {list_molecules()}"
        )
    return MOLECULES[name]